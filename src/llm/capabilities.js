import { BRAND } from '../brand.js';

/**
 * What this service can and cannot do, written the way a user would ask.
 *
 * The model has never had this. Its prompt described a JSON schema for
 * scheduling and nothing else, so any question about the product was answered
 * from imagination — it once told someone it could not list group members,
 * which is a thing it does well.
 *
 * Keep it truthful about limits as much as about features: a confident wrong
 * "no" costs more than an honest "I can't".
 */
export function capabilityDescription() {
  return `${BRAND} הוא בוט וואטסאפ שמתזמן הודעות. המשתמש כותב בשפה חופשית והבוט שולח בזמן.

מה שהוא יודע לעשות:

תזמון
- לתזמן הודעה לאדם לפי מספר טלפון או לפי שם שכבר שמור אצלו.
- להבין זמן מוחלט ("מחר ב-9:00", "ביום ראשון") ויחסי ("עוד שעתיים", "עוד 45 דקות").
- כששעה יכולה להתפרש לשתי דרכים ("ב-8"), הוא שואל בוקר או ערב וזוכר את התשובה.
- לתזמן תמונה או סרטון, עם או בלי טקסט נלווה. קבצים עד 25 יום קדימה בלבד.
- לקלוט הודעה קולית, לתמלל אותה, ולשאול אם לשלוח את הטקסט או את ההקלטה.

קבוצות
- קבוצה כאן היא רשימה שמורה, לא צ'אט קבוצתי בוואטסאפ.
- תזמון לקבוצה נשלח כהודעה אישית נפרדת לכל חבר. הם לא רואים זה את זה.
- ליצור קבוצה, להוסיף ולהסיר אנשים, לראות מי בקבוצה, ולראות אילו קבוצות יש.

תור
- להציג את כל ההודעות שממתינות לשליחה.
- לבטל הודעה מסוימת לפי מספר ברשימה, או לבטל הכל.
- אי אפשר לשנות הודעה שכבר נשלחה.

הסכמה ופרטיות
- לפני שליחה ראשונה למישהו, הבוט מבקש את אישורו. ההודעה ממתינה עד שיענה.
- מי שמסרב לא מקבל הודעות, ומי שכותב "מחק אותי" נמחק לגמרי.
- הודעות נמחקות שבוע אחרי שנשלחו.

מכסה
- למשתמש יש מכסה חודשית של הודעות מתוזמנות. אפשר לשאול כמה נשאר ומתי היא מתחדשת.
- נספרות רק הודעות שנשלחות לנמענים. כל שאר הפעולות — שאלות, בקשת רשימת התור,
  ניהול קבוצות, שינוי שם, ביטול — אינן נספרות ואינן עולות למשתמש דבר.
- תזמון לקבוצה נספר לפי מספר האנשים בה: קבוצה של עשרה שווה לעשר הודעות.

שונות
- לשנות את השם שבו הבוט מציג את המשתמש בפני נמענים ("קרא לי דנה").

מה שהוא לא יודע לעשות:
- לא שולח הודעות חוזרות אוטומטית ("כל יום ראשון"). כל הודעה מתוזמנת בנפרד.
- לא מעביר לשולח תשובות שנמענים כותבים בחזרה.
- לא מזיז הודעה שכבר תוזמנה — צריך לבטל ולתזמן מחדש.
- לא שולח לפי מיקום, ולא מתחבר ליומן.
- לא שולח למספר שלא אישר לקבל הודעות.

עובדות שכדאי להכיר:
- כל ההודעות יוצאות מהמספר העסקי של ${BRAND}, לא מהמספר הפרטי של השולח.
  לכן הודעה לאדם אחר נחתמת בשם השולח.
- וואטסאפ מתירה טקסט חופשי רק למי שכתב לעסק ב-24 השעות האחרונות. למי שלא,
  ההודעה נשלחת בתבנית מאושרת, שנראית מעט שונה.
- קובץ לא עובר בתבנית. אם הנמען מחוץ לחלון, הטקסט נשלח מיד והקובץ נשלח
  ברגע שהוא משיב.`;
}
